import { describe, expect, it } from "vitest";
import manifest from "@/app/manifest";
import { APP_NAME } from "@/config/app";

describe("the installable app (manifest, D-031)", () => {
  it("opens on the dashboard, full screen, inside its own scope", () => {
    const m = manifest();
    expect(m).toMatchObject({ name: APP_NAME, display: "standalone", start_url: "/dashboard", scope: "/" });
    expect(String(m.start_url).startsWith(String(m.scope))).toBe(true);
  });

  it("has the icons phones ask for: 192 and 512, and one they may crop to their own shape", () => {
    const icons = manifest().icons ?? [];
    expect(icons.map((i) => i.sizes)).toEqual(expect.arrayContaining(["192x192", "512x512"]));
    expect(icons.some((i) => i.purpose === "maskable")).toBe(true);
    for (const i of icons) expect(i.src).toMatch(/^\/icon\/(192|512)$/); // generated by src/app/icon.tsx
  });
});
